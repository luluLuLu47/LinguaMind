export function getRandomTheme(excludeId?: string): WordTheme {
  const pool = WORD_THEMES.filter(t => t.id !== excludeId)
  if (pool.length === 0) return WORD_THEMES[0]
  return pool[Math.floor(Math.random() * pool.length)]
}

export function getThemeById(id: string): WordTheme | undefined {
  return WORD_THEMES.find(t => t.id === id)
}

